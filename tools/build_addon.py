#!/usr/bin/env python3
"""TIOW Inbox is delivered as one file (addons/tiow_inbox.py) but edited in sections (addons/tiow_inbox_src/NN_*.py),
so a change means reading one section, not 226 KB. The sections are the file cut at its '# ------ title' banners;
joined in order they give the file back byte for byte.

  python3 tools/build_addon.py            sections -> addons/tiow_inbox.py   (after editing a section)
  python3 tools/build_addon.py --split    addons/tiow_inbox.py -> sections   (after the file itself was edited)
  python3 tools/build_addon.py --check    exit 1 if they differ
Each run also rewrites tiow_inbox_src/INDEX.md: every function and class, its section and line count. Read that
first to find where something lives. A section is not importable by itself. Standard library only."""
import os, re, sys
R = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
ONE, SRC = os.path.join(R, "addons", "tiow_inbox.py"), os.path.join(R, "addons", "tiow_inbox_src")
BANNER = re.compile(r"^# -{40,} (.+?)\s*$")


def sections(text):
    out, cur, title = [], [], "header"
    for line in text.split("\n"):
        m = BANNER.match(line)
        if m and cur:
            out.append((title, cur)); cur, title = [], m.group(1)
        cur.append(line)
    out.append((title, cur))
    return [("%02d_%s.py" % (i, re.sub(r"[^a-z0-9]+", "_", t.lower()).strip("_")[:40]), "\n".join(c))
            for i, (t, c) in enumerate(out)]


def joined():
    names = sorted(f for f in os.listdir(SRC) if re.match(r"\d\d_.*\.py$", f))
    return "\n".join(open(os.path.join(SRC, f), encoding="utf-8", newline="").read() for f in names)


def index(parts):
    L = ["# TIOW Inbox: where things are", "",
         "Generated by `tools/build_addon.py`. Edit a section, then run it to rebuild `addons/tiow_inbox.py`.", ""]
    for name, text in parts:
        lines = text.split("\n")
        defs = [(i, m.group(2)) for i, l in enumerate(lines) for m in [re.match(r"(def|class) (\w+)", l)] if m]
        L.append("## %s (%d lines)" % (name, len(lines)))
        L.append(", ".join("`%s` %d" % (n, (defs[k + 1][0] if k + 1 < len(defs) else len(lines)) - i)
                           for k, (i, n) in enumerate(defs)) or "(data)")
        L.append("")
    open(os.path.join(SRC, "INDEX.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L))


def main():
    one = open(ONE, encoding="utf-8", newline="").read()
    if "--split" in sys.argv or not os.path.isdir(SRC):
        os.makedirs(SRC, exist_ok=True)
        parts = sections(one)
        for f in os.listdir(SRC):
            if f.endswith(".py") and f not in dict(parts): os.remove(os.path.join(SRC, f))
        for name, text in parts: open(os.path.join(SRC, name), "w", encoding="utf-8", newline="").write(text)
        index(parts); print("split into %d sections" % len(parts)); return
    j = joined()
    if "--check" in sys.argv:
        if j != one: print("addons/tiow_inbox.py and tiow_inbox_src differ: run tools/build_addon.py (or --split)"); sys.exit(1)
        print("add-on sections match the file"); return
    if j != one: open(ONE, "w", encoding="utf-8", newline="").write(j)
    index(sections(j)); print("built addons/tiow_inbox.py" + ("" if j != one else " (unchanged)"))


if __name__ == "__main__":
    main()
